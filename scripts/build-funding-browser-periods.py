"""Bundle funding-period annotations and review status without rewriting research records."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'data/funding-browser-periods.json').read_text())
assert len(data['records'])==31
assert len({r['key'] for r in data['records']})==31
batch_ids={batch['id'] for batch in data['accepted_batches']}
for row in data['records']:
    period=row['programPeriod']
    assert row['scope'] in ['tucson','phoenix']
    assert not row['id'].startswith('TEST-')
    assert row['review']['status'] in ['awaiting_handoff','accepted_handoff']
    if row['review']['status']=='accepted_handoff':
        assert row['review']['batch_id'] in batch_ids
        assert row['review']['source_basis']
        assert period.get('evidence')
        assert all(e.get('url','').startswith('https://') and e.get('locator') for e in period['evidence'])
        assert isinstance(period.get('hasUnknownComponent'), bool)
        for part in period.get('periods', []):
            if part['status'] in ['unknown', 'not_established', 'not_applicable']:
                assert not part['years']
            else:
                assert part['status']=='verified' and part['evidence']
                assert set(part['years'])=={m['year'] for m in part['yearMatches']}
                assert all(m['basis'] in ['calendar_overlap','source_year_label'] for m in part['yearMatches'])
        if period['status']=='not_applicable':
            assert not period['years'] and not period['hasUnknownComponent']
    assert len(period['years'])==len(set(period['years']))
    assert all(len(y)==4 and y.isdecimal() for y in period['years'])
    assert period['label'] and period['explanation']
    if not period['years'] and period['status']!='not_applicable':
        assert period['label']=='Unknown / not established'
encoded=json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')
(root/'assets/funding-periods-data.js').write_text('/* Generated by scripts/build-funding-browser-periods.py. */\nwindow.HAP_FUNDING_PERIODS_DATA='+encoded+';\n')
print('Bundled 31 separate funding-period annotations; review status is retained for each record.')

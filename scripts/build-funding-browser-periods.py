"""Bundle funding-period annotations and review status without rewriting research records."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'data/funding-browser-periods.json').read_text())
assert len(data['records'])==31
assert len({r['key'] for r in data['records']})==31
for row in data['records']:
    period=row['programPeriod']
    assert row['scope'] in ['tucson','phoenix']
    assert len(period['years'])==len(set(period['years']))
    assert all(len(y)==4 and y.isdecimal() for y in period['years'])
    assert period['label'] and period['explanation']
    if not period['years'] and period['status']!='not_applicable':
        assert period['label']=='Unknown / not established'
encoded=json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')
(root/'assets/funding-periods-data.js').write_text('/* Generated by scripts/build-funding-browser-periods.py. */\nwindow.HAP_FUNDING_PERIODS_DATA='+encoded+';\n')
print('Bundled 31 separate funding-period annotations; review status is retained for each record.')

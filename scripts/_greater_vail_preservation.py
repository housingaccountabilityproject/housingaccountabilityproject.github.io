@lru_cache(maxsize=None)
def _baseline(root, name):
    # Only immutable Git blobs are cached; live files and diff scope are not.
    value = subprocess.check_output(['git', 'show', VAIL_BASE + ':' + name], cwd=root)
    if name in BASE_SHA256:
        assert hashlib.sha256(value).hexdigest() == BASE_SHA256[name], ('Unverified Vail base', name)
    return value


def baseline(root, name):
    return _baseline(str(Path(root).resolve()), name)


def _index_bytes(value):
    encoded = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
    encoded = encoded.replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    return ('/* Generated by scripts/build-reader-data.py. Do not edit. */\nwindow.HAP_SEARCH_INDEX=' + encoded + ';\n').encode()


def expected_public(root):
    expected = {}
    for name in ('_data/tucson_weatherization_and_vail_resources.html', 'housing-help.html'):
        before = baseline(root, name)
        assert before.count(BEFORE_CARD) == 1, ('Ambiguous reviewed Vail card', name)
        expected[name] = before.replace(BEFORE_CARD, AFTER_CARD, 1)
    original_index = baseline(root, 'assets/search-index.js')
    data = json.loads(original_index.decode().split('window.HAP_SEARCH_INDEX=', 1)[1].rstrip(';\n'))
    assert _index_bytes(data) == original_index, 'Unverified index serialization'
    assert len(data['records']) == 382, 'Unexpected frozen index count'
    positions = [i for i, row in enumerate(data['records']) if row['url'] == REVIEWED_SEARCH_RECORD['url']]
    assert len(positions) == 1, 'Expected exactly one existing Vail search record'
    position = positions[0]
    before_record = data['records'][position]
    assert {k: v for k, v in before_record.items() if k != 'text'} == {
        k: v for k, v in REVIEWED_SEARCH_RECORD.items() if k != 'text'
    }, 'Vail record identity or metadata changed'
    successor = deepcopy(data)
    successor['records'][position] = deepcopy(REVIEWED_SEARCH_RECORD)
    coverage = [i for i, row in enumerate(successor['coverage']) if row['page'] == 'housing-help.html']
    assert len(coverage) == 1 and successor['coverage'][coverage[0]] == BEFORE_COVERAGE
    successor['coverage'][coverage[0]] = deepcopy(AFTER_COVERAGE)
    expected['assets/search-index.js'] = _index_bytes(successor)
    old_coverage = baseline(root, 'data/search-coverage.json')
    rows = json.loads(old_coverage)
    assert (json.dumps(rows, indent=2) + '\n').encode() == old_coverage
    positions = [i for i, row in enumerate(rows) if row['page'] == 'housing-help.html']
    assert len(positions) == 1 and rows[positions[0]] == BEFORE_COVERAGE
    rows[positions[0]] = deepcopy(AFTER_COVERAGE)
    expected['data/search-coverage.json'] = (json.dumps(rows, indent=2) + '\n').encode()
    return expected


def _replace_once(value, before, after):
    assert value.count(before) == 1, ('Ambiguous frozen validation edit', before)
    return value.replace(before, after, 1)


def expected_workflows(root):
    # Phoenix is globally required: preserve every job/permission byte and remove
    # only its PR path restriction. The Reader addition is focused PR evidence.
    phoenix = baseline(root, '.github/workflows/phoenix-records-qa.yml')
    start = phoenix.index(b'    paths:\n')
    end = phoenix.index(b'  workflow_dispatch:\n')
    phoenix = phoenix[:start] + phoenix[end:]
    reader = baseline(root, '.github/workflows/reader-tools-qa.yml')
    marker = b'      - uses: actions/upload-artifact@v4\n        if: always()\n'
    step = (b'      - name: Verify reviewed Greater Vail in production Pages output\n'
            b'        if: ${{ !cancelled() }}\n'
            b'        run: node scripts/_test-greater-vail.mjs\n')
    reader = _replace_once(reader, marker, step + marker)
    reader = _replace_once(reader, b'            /tmp/hap-category-search/\n',
                           b'            /tmp/hap-category-search/\n            /tmp/hap-greater-vail/\n')
    return {'.github/workflows/phoenix-records-qa.yml': phoenix,
            '.github/workflows/reader-tools-qa.yml': reader}


def org_successor(original):
    original = _replace_once(
        original,
        b'from site_inspection_preservation import RELEASE_BASE, VALIDATION_PATHS, released_source\n',
        b'from site_inspection_preservation import RELEASE_BASE, VALIDATION_PATHS, released_source, verify_release\n')
    return _replace_once(original, b'def verify_transition(root, expected_digest):\n',
                         b'def verify_transition(root, expected_digest):\n    verify_release(root)\n')


def inspection_successor(original, guard_digest, org_digest):
    assert len(guard_digest) == len(org_digest) == 64
    insertion = ("from _greater_vail_preservation import predecessor as vail_predecessor, verify_transition as verify_vail_transition\n\n"
                 "GREATER_VAIL_GUARD_SHA256 = '" + guard_digest + "'\n").encode()
    original = _replace_once(original, b'import subprocess\n', b'import subprocess\n' + insertion)
    old_line = next(line for line in original.splitlines(keepends=True) if line.startswith(b'VALIDATION_HASHES = '))
    pins = ast.literal_eval(old_line.decode().partition(' = ')[2])
    pins['scripts/org_search_preservation.py'] = org_digest
    original = _replace_once(original, old_line, ('VALIDATION_HASHES = ' + repr(pins) + '\n').encode())
    original = _replace_once(original, b'    current = (root / name).read_bytes()\n',
                             b'    current = vail_predecessor(root, name, GREATER_VAIL_GUARD_SHA256)\n')
    original = _replace_once(original, b'def verify_release(root):\n',
                             b'def verify_release(root):\n    vail_paths = verify_vail_transition(root, GREATER_VAIL_GUARD_SHA256)\n')
    return _replace_once(original, b'    expected = set(REVIEWED) | VALIDATION_PATHS\n',
                          b'    expected = set(REVIEWED) | VALIDATION_PATHS | vail_paths\n')


def _verify_guard(root, guard_digest):
    assert hashlib.sha256((root / GUARD_PATH).read_bytes()).hexdigest() == guard_digest, 'Unreviewed Vail validation module'


def predecessor(root, name, guard_digest):
    current = (root / name).read_bytes()
    if name not in PUBLIC_PATHS:
        return current
    _verify_guard(root, guard_digest)
    assert current == expected_public(root)[name], ('Unreviewed Vail content, record or surrounding bytes', name)
    return baseline(root, name)


def verify_transition(root, guard_digest):
    _verify_guard(root, guard_digest)
    expected_paths = PUBLIC_PATHS | VALIDATION_PATHS | WORKFLOW_PATHS
    changed = set(subprocess.check_output(['git', 'diff', '--name-only', VAIL_BASE, '--'], cwd=root, text=True).splitlines())
    untracked = set(subprocess.check_output(['git', 'ls-files', '--others', '--exclude-standard'], cwd=root, text=True).splitlines())
    assert changed | untracked == expected_paths, ('Unexpected Vail transition paths', sorted((changed | untracked) ^ expected_paths))
    for name in expected_paths:
        assert (root / name).is_file() and not (root / name).is_symlink(), ('Unexpected Vail file type', name)
    for line in subprocess.check_output(['git', 'diff', '--raw', VAIL_BASE, '--'], cwd=root, text=True).splitlines():
        modes = line.split()[:2]
        assert modes in ([':100644', '100644'], [':000000', '100644']), ('Unexpected Vail file mode', line)
    expected = expected_public(root)
    expected.update(expected_workflows(root))
    assert hashlib.sha256((root / 'scripts/_test-greater-vail.mjs').read_bytes()).hexdigest() == VAIL_BROWSER_SHA256, 'Unreviewed focused Vail browser test'
    for name, content in expected.items():
        assert (root / name).read_bytes() == content, ('Unreviewed Vail content, record or surrounding bytes', name)
    org = org_successor(baseline(root, 'scripts/org_search_preservation.py'))
    assert (root / 'scripts/org_search_preservation.py').read_bytes() == org, 'Unreviewed .org guard integration'
    inspection = inspection_successor(baseline(root, 'scripts/site_inspection_preservation.py'), guard_digest,
                                      hashlib.sha256(org).hexdigest())
    assert (root / 'scripts/site_inspection_preservation.py').read_bytes() == inspection, 'Unreviewed #64 guard integration'
    print('PASS exact Vail transition: one reviewed resource/search update; 381 other records, adjacent bytes and frozen #64/historical checks preserved.')
    return expected_paths

#!/usr/bin/env python3
"""Reconcile the curated public extract with canonical records, then bundle it."""
from copy import deepcopy
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]

def read(name):
    return json.loads((ROOT / name).read_text())

def strings(value):
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        return [text for item in value for text in strings(item)]
    if isinstance(value, dict):
        return [text for item in value.values() for text in strings(item)]
    return []

def bundle(name, variable, value):
    encoded = json.dumps(value, ensure_ascii=False, separators=(',', ':'))
    encoded = encoded.replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    (ROOT / name).write_text(f'/* Generated by scripts/build-category-search.py. */\nwindow.{variable}={encoded};\n')

data = read('data/category-search.json')
phoenix = read('data/phoenix-records.json')
metadata = read('data/phoenix-source-metadata.json')
periods = {row['key']: row for row in read('data/funding-periods.json')['records']}
source_rows = {row['public_id']: row for row in read('data/source-register.json')['sources']}
record_rows = {row['id']: row for row in phoenix['records']}
known = {row['key'] for row in data['records']}
proposal = record_rows['MC-PLAN-WEB-001']
if 'phoenix:MC-PLAN-WEB-001' not in known:
    data['records'].append({
        'key': 'phoenix:MC-PLAN-WEB-001', 'id': 'MC-PLAN-WEB-001',
        'anchor': 'MC-PLAN-WEB-001', 'scope': 'phoenix', 'category': 'sources',
        'title': proposal['title'], 'kind': 'Proposed plan amendment',
        'sourceType': 'Official notices', 'topics': ['Maricopa County planning'],
        'agency': 'Maricopa County', 'programs': ['HOME', 'CDBG', 'ESG'],
        'years': ['2025', '2029'], 'label': 'Proposed; adoption unverified',
        'summary': [], 'caveats': [], 'notes': [], 'metadata': [],
        'url': 'https://housingaccountabilityproject.github.io/phoenix/records.html#MC-PLAN-WEB-001',
        'contextUrl': 'https://housingaccountabilityproject.github.io/phoenix/index.html#MC-PLAN-WEB-001',
        'originals': [], 'links': [], 'sourceIds': ['MC-PLAN-001'], 'aliases': [],
        'raw': {}, 'yearBasis': 'Proposed plan coverage',
        'yearNote': '2025–2029 is proposed plan coverage, not an adopted funding or assistance period.',
        'yearEvidence': [],
    })
for row in data['records']:
    if row['key'] in periods:
        for field in ['programPeriod', 'knownDates', 'periodLeads']:
            row[field] = deepcopy(periods[row['key']].get(field, []))
    if row['scope'] == 'phoenix' and row['id'] in record_rows:
        record = record_rows[row['id']]
        row['raw'] = deepcopy(record)
        row['summary'] = record['summary']
        row['caveats'] = record['limitations']
        row['notes'] = list(dict.fromkeys([*record['context'], *row['notes']]))
        row['sourceIds'] = record['source_ids']
        if 'citations' in record:
            row['originals'] = [{'title': item['title'], 'url': item['url']} for item in record['citations']]
    if row['scope'] == 'phoenix' and row['id'] in metadata['sources']:
        source = metadata['sources'][row['id']]
        row['agency'] = metadata['agencies'][source['agency']]
        row['programs'] = [metadata['programs'][name] for name in source['programs']]
        row['raw']['metadata'] = deepcopy(source)
        if source.get('verification_checks'):
            row['verificationChecks'] = deepcopy(source['verification_checks'])
    if row['scope'] == 'tucson' and row['id'] in source_rows:
        source = source_rows[row['id']]
        if source.get('document_date'):
            row['documentDate'] = source['document_date']
        if source.get('verification_checks'):
            row['verificationChecks'] = source['verification_checks']
    if row.get('yearSourceCheck'):
        row['yearSourceCheck'] = row['yearSourceCheck'].replace('(UTC)', '(recorded date; exact check instant was not retained)')
    row['metadata'] = [[('Recorded retrieval date' if key == 'Recorded review' else key), value] for key, value in row['metadata']]
    row['searchText'] = ' '.join(strings({key: value for key, value in row.items() if key not in {'raw', 'searchText'}}))
data['researchSnapshots'] = {'phoenix': phoenix['research_snapshot'], 'tucson': read('data/city-reader-guide.json')['cities']['tucson']['date']}
for scope in ['tucson', 'phoenix']:
    selected = [row for row in data['records'] if row['scope'] == scope]
    counts = {category: sum(row['category'] == category for row in selected) for category in ['funding', 'sources', 'questions', 'updates']}
    data['coverage'][scope] = f"{len(selected)} public entries. {counts['funding']} funding entries, {counts['sources']} source and evidence entries, {counts['questions']} questions and {counts['updates']} updates. Selected records are not complete program or year coverage."
(ROOT / 'data/category-search.json').write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
bundle('assets/category-search-data.js', 'HAP_CATEGORY_SEARCH_DATA', data)
coverage = read('data/search-coverage.json')
bundle('assets/category-search-coverage.js', 'HAP_FULL_SEARCH_COVERAGE', {'records': sum(page['records'] for page in coverage), 'pages': len(coverage)})
bundle('assets/funding-program-names.js', 'HAP_FUNDING_PROGRAM_NAMES', read('data/funding-program-names.json'))
print(f"Bundled {len(data['records'])} public records with visible agencies, programs and source-backed date roles.")

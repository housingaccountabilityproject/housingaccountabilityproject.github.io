#!/usr/bin/env python3
"""Bundle the reviewed public-only category snapshot. No source dates are inferred."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'data/category-search.json').read_text())
text=json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c').replace('\u2028','\\u2028').replace('\u2029','\\u2029')
(ROOT/'assets/category-search-data.js').write_text('/* Generated by scripts/build-category-search.py. */\nwindow.HAP_CATEGORY_SEARCH_DATA='+text+';\n')
coverage=json.loads((ROOT/'data/search-coverage.json').read_text())
with (ROOT/'assets/category-search-coverage.js').open('w') as output: output.write('window.HAP_FULL_SEARCH_COVERAGE='+json.dumps({'records':sum(p['records'] for p in coverage),'pages':len(coverage)},separators=(',',':'))+';\n')
print('Bundled',len(data['records']),'public records.')

programs=json.loads((ROOT/'data/funding-program-names.json').read_text())
(ROOT/'assets/funding-program-names.js').write_text('/* Named programs from the existing reviewed public funding evidence. */\nwindow.HAP_FUNDING_PROGRAM_NAMES='+json.dumps(programs,ensure_ascii=False,separators=(',',':'))+';\n')
